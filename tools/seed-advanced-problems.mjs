async function add(
  id,
  title,
  topic,
  track,
  signature,
  body,
  visible,
  hidden,
  statement,
  examples,
  hints,
  editorial,
  shape,
  stability,
  production,
  complexity,
) {
  const p = {
    id,
    title,
    topic,
    track,
    difficulty: 4,
    labs: ["General"],
    minutes: 35,
    signature,
    starter: signature + "\n    pass\n",
    visible,
    statement,
    constraints:
      "Finite numeric inputs satisfying the stated shapes. Do not mutate inputs. Invalid shapes or weights must raise ValueError where specified. Match floating results within 1e-8.",
    examples,
    hints,
    editorial,
    shape,
    stability,
    production,
    complexity,
    prerequisites: [String(track)],
    mistakes: [
      "Ignoring a shape or boundary condition",
      "Using a mathematically correct but numerically unstable expression",
      "Mutating caller-owned state",
    ],
  };
  additions.push(p);
  await writeFile(
    new URL(`../content/solutions/${id}.json`, import.meta.url),
    JSON.stringify({ reference: signature + "\n" + body, hidden }, null, 2) +
      "\n",
  );
}
